export default function NavigasiUtama() {
  const navigate = useNavigate()
  const location = useLocation()

  const menus = [
    { id: 'beranda', label: 'Beranda', path: '/' },
    { id: 'materi', label: 'Materi Klinis', path: '/materi-komunikasi' },
    { id: 'respons', label: 'Respons Pasien', path: '/respons-pasien' },
    { id: 'pengaturan', label: 'Pengaturan', path: '/pengaturan' }
  ]

  const isActive = (path) => {
    if (path === '/') return location.pathname === '/'
    return location.pathname.startsWith(path)
  }

  return (
    <nav className="nav-utama">
      {menus.map(menu => (
        <button
          key={menu.id}
          className={`nav-item ${isActive(menu.path) ? 'nav-item--active' : ''}`}
          onClick={() => navigate(menu.path)}
        >
          <span className="nav-ikon">
            <NavIkon nama={menu.id} />
          </span>
          <span className="nav-label">{menu.label}</span>
        </button>
      ))}
    </nav>
  )
}

